import "server-only"; // boundary: never import this module from a Client Component

// Roadmap output validation. The model's output is untrusted: everything is
// re-typed, bounded, and normalized here before it is ever shown to the user
// or persisted. Server generates database IDs after validation — the model
// never supplies trusted IDs, so prerequisites are referenced by global step
// number and resolved to real step ids at persist time.

import { z } from "zod";
import { AIAppError } from "./config.js";

// ---- request input schemas (client → server) -------------------------------
const optionalLevel = z
  .string()
  .trim()
  .toLowerCase()
  .refine((v) => ["beginner", "intermediate", "advanced", "job_ready"].includes(v), {
    message: "Unknown level",
  })
  .nullable()
  .optional();

export const roadmapInputSchema = z.object({
  goal: z.string().trim().min(4, "Describe your goal in a few words").max(300),
  current_level: optionalLevel,
  target_level: optionalLevel,
  deadline: z
    .string()
    .regex(/^\d{4}-\d{2}-\d{2}$/, "Use YYYY-MM-DD")
    .nullable()
    .optional(),
  known_topics: z.string().trim().max(600).nullable().optional(),
  constraints: z.string().trim().max(600).nullable().optional(),
  // Optional: a learner-provided roadmap in plain text. When present, the
  // model converts/structures it into the draft format instead of inventing a
  // new plan from scratch. Bounded to fit the request envelope.
  source_text: z.string().trim().max(20_000).nullable().optional(),
  weekly_study_minutes: z.number().int().min(0).max(10_080).nullable().optional(),
  study_days: z.array(z.number().int().min(0).max(6)).max(7).nullable().optional(),
  collection_title: z.string().trim().max(140).nullable().optional(),
});

export const stageInputSchema = z.object({
  goal: z.string().trim().min(4).max(300),
  stage_title: z.string().trim().min(2).max(140),
  stage_context: z.string().trim().max(600).nullable().optional(),
  weekly_study_minutes: z.number().int().min(0).max(10_080).nullable().optional(),
});

// ---- bounds (keep drafts reviewable and quota-friendly) --------------------
const LIMITS = {
  title: 140,
  description: 600,
  objective: 300,
  assumption: 220,
  rationale: 800,
  stages: 8,
  milestonesPerStage: 6,
  stepsPerMilestone: 8,
  assumptions: 6,
  minutesMin: 5,
  minutesMax: 600,
  totalMinutesMax: 200_000,
};

const cleanText = (max) =>
  z
    .string()
    .transform((s) => s.replace(/\s+/g, " ").trim())
    .refine((s) => s.length > 0 && s.length <= max, {
      message: `Must be 1–${max} characters`,
    });

const cleanOptionalText = (max) =>
  z
    .string()
    .transform((s) => s.replace(/\s+/g, " ").trim())
    .refine((s) => s.length <= max, { message: `Max ${max} characters` })
    .transform((s) => s || null)
    .nullable()
    .catch(null);

const minutes = z
  .number()
  .finite()
  .transform((n) => Math.round(n))
  .refine((n) => n >= LIMITS.minutesMin && n <= LIMITS.minutesMax, {
    message: `Estimated minutes must be ${LIMITS.minutesMin}–${LIMITS.minutesMax}`,
  });

const LEVELS = ["beginner", "intermediate", "advanced"];
const TASK_TYPES = ["study", "practice", "project", "review"];

const level = z
  .string()
  .trim()
  .toLowerCase()
  .refine((v) => LEVELS.includes(v), { message: "Unknown level" })
  .nullable()
  .catch(null);

const taskType = z
  .string()
  .trim()
  .toLowerCase()
  .refine((v) => TASK_TYPES.includes(v), { message: "Unknown task type" })
  .catch("study");

const stepSchema = z.object({
  title: cleanText(LIMITS.title),
  description: cleanOptionalText(LIMITS.description),
  learning_objective: cleanOptionalText(LIMITS.objective),
  estimated_minutes: minutes.catch(30),
  difficulty: level.catch("beginner"),
  task_type: taskType,
  // 1-based global step numbers within the same draft; validated + resolved
  // server-side ("IDs are generated by the server after validation").
  prerequisite_steps: z.array(z.number().int().positive()).max(10).catch([]),
});

const milestoneSchema = z.object({
  title: cleanText(LIMITS.title),
  description: cleanOptionalText(LIMITS.description),
  steps: z.array(stepSchema).min(1).max(LIMITS.stepsPerMilestone),
});

const stageSchema = z.object({
  title: cleanText(LIMITS.title),
  description: cleanOptionalText(LIMITS.description),
  milestones: z.array(milestoneSchema).min(1).max(LIMITS.milestonesPerStage),
});

export const roadmapDraftSchema = z.object({
  title: cleanText(LIMITS.title),
  goal: cleanText(LIMITS.title),
  rationale: cleanOptionalText(LIMITS.rationale),
  assumptions: z
    .array(cleanText(LIMITS.assumption))
    .max(LIMITS.assumptions)
    .catch([]),
  estimated_total_minutes: z
    .number()
    .finite()
    .transform((n) => Math.round(n))
    .refine((n) => n > 0 && n <= LIMITS.totalMinutesMax, {
      message: "Total estimate out of range",
    })
    .catch(null),
  current_level: level,
  target_level: level,
  stages: z.array(stageSchema).min(1).max(LIMITS.stages),
});

export const stageDraftSchema = z.object({
  title: cleanText(LIMITS.title),
  description: cleanOptionalText(LIMITS.description),
  milestones: z.array(milestoneSchema).min(1).max(LIMITS.milestonesPerStage),
});

/**
 * Pull the JSON object out of model content. Handles ```json fences and
 * leading/trailing prose. Throws AIAppError(AI_INVALID_RESPONSE) when no
 * parseable object is found.
 */
function extractJson(content) {
  const fenced = /```(?:json)?\s*([\s\S]*?)```/.exec(content);
  const candidate = (fenced?.[1] ?? content).trim();
  const start = candidate.indexOf("{");
  const end = candidate.lastIndexOf("}");
  if (start === -1 || end <= start) {
    throw new AIAppError(
      "AI_INVALID_RESPONSE",
      "An unexpected response was returned. Please try again."
    );
  }
  try {
    return JSON.parse(candidate.slice(start, end + 1));
  } catch {
    throw new AIAppError(
      "AI_INVALID_RESPONSE",
      "An unexpected response was returned. Please try again."
    );
  }
}

/** Normalize + renumber a validated draft; returns null on cycles. */
function renumber(stages) {
  let stepNumber = 0;
  const stepsByNumber = new Map(); // number -> {node, prereqs}
  const normalized = stages.map((stage, stageIdx) => ({
    title: stage.title,
    description: stage.description,
    milestones: stage.milestones.map((milestone, milestoneIdx) => ({
      title: milestone.title,
      description: milestone.description,
      steps: milestone.steps.map((step) => {
        stepNumber += 1;
        const node = {
          ...step,
          prerequisite_steps: [...new Set(step.prerequisite_steps)],
        };
        stepsByNumber.set(stepNumber, node);
        return node;
      }),
      order_index: milestoneIdx + 1,
    })),
    order_index: stageIdx + 1,
  }));

  // Prerequisites must point at valid steps and must not create cycles.
  // Self-references are trivially cycles.
  for (const [number, node] of stepsByNumber) {
    if (
      node.prerequisite_steps.some(
        (p) => p === number || !stepsByNumber.has(p)
      )
    ) {
      return null;
    }
  }

  const state = new Map(); // number -> "visiting" | "ok"
  const visit = (number) => {
    const mark = state.get(number);
    if (mark === "ok") return true;
    if (mark === "visiting") return false; // cycle
    state.set(number, "visiting");
    for (const p of stepsByNumber.get(number).prerequisite_steps) {
      if (!visit(p)) return false;
    }
    state.set(number, "ok");
    return true;
  };
  for (const number of stepsByNumber.keys()) {
    if (!visit(number)) return null;
  }

  return normalized;
}

/**
 * Validate + normalize a full roadmap draft from model content.
 * @returns {{title, goal, rationale, assumptions, estimated_total_minutes,
 *   current_level, target_level, stages}} — stages renumbered 1..n, steps
 *   numbered globally in `step_number`, prerequisites cycle-checked.
 */
export function parseRoadmapDraft(content) {
  let parsed;
  try {
    parsed = roadmapDraftSchema.parse(extractJson(content));
  } catch (error) {
    if (error instanceof AIAppError) throw error;
    throw new AIAppError(
      "AI_INVALID_RESPONSE",
      "An unusable roadmap was returned. Please try again."
    );
  }

  const stages = renumber(parsed.stages);
  if (!stages) {
    throw new AIAppError(
      "AI_INVALID_RESPONSE",
      "Invalid step ordering was returned. Please try again."
    );
  }

  let stepNumber = 0;
  for (const stage of stages) {
    for (const milestone of stage.milestones) {
      for (const step of milestone.steps) {
        stepNumber += 1;
        step.step_number = stepNumber;
      }
    }
  }

  const totalFromSteps = stages.reduce(
    (sum, s) =>
      sum +
      s.milestones.reduce(
        (ms, m) => ms + m.steps.reduce((ss, st) => ss + st.estimated_minutes, 0),
        0
      ),
    0
  );

  return {
    title: parsed.title,
    goal: parsed.goal,
    rationale: parsed.rationale,
    assumptions: parsed.assumptions,
    estimated_total_minutes: parsed.estimated_total_minutes ?? totalFromSteps,
    current_level: parsed.current_level,
    target_level: parsed.target_level,
    stages,
  };
}

/**
 * Validate + normalize a single regenerated stage. Local step numbers
 * (1..n within the stage) are returned; the client maps prerequisite
 * numbers onto the full draft when the user accepts the replacement.
 */
export function parseStageDraft(content) {
  let parsed;
  try {
    parsed = stageDraftSchema.parse(extractJson(content));
  } catch (error) {
    if (error instanceof AIAppError) throw error;
    throw new AIAppError(
      "AI_INVALID_RESPONSE",
      "An unusable stage was returned. Please try again."
    );
  }

  let local = 0;
  const milestones = parsed.milestones.map((milestone, milestoneIdx) => ({
    title: milestone.title,
    description: milestone.description,
    order_index: milestoneIdx + 1,
    steps: milestone.steps.map((step) => ({
      ...step,
      // A regenerated stage is standalone: the model can't know global step
      // numbers, so its references are meaningless. Prerequisites start
      // empty; the user (or a later adapt pass) can wire ordering.
      prerequisite_steps: [],
      local_number: ++local,
    })),
  }));

  // Local prerequisite numbers (1..n within the stage), cycle-checked.
  const flat = milestones.flatMap((m) => m.steps);
  for (const step of flat) {
    const localRefs = step.prerequisite_steps.filter(
      (p) => p !== step.local_number && p >= 1 && p <= flat.length
    );
    step.prerequisite_steps = [...new Set(localRefs)];
  }
  const seen = new Map();
  const visit = (number) => {
    const mark = seen.get(number);
    if (mark === "ok") return true;
    if (mark === "visiting") return false;
    seen.set(number, "visiting");
    for (const p of flat[number - 1].prerequisite_steps) {
      if (!visit(p)) return false;
    }
    seen.set(number, "ok");
    return true;
  };
  if (flat.some((step) => !visit(step.local_number))) {
    // Cyclic local prerequisites: drop them rather than reject an otherwise
    // usable stage — the user reviews and edits ordering anyway.
    for (const step of flat) step.prerequisite_steps = [];
  }

  return {
    title: parsed.title,
    description: parsed.description,
    milestones,
  };
}
